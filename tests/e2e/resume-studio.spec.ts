test('makes independent JSON copies, restores edits, exports a PDF and freezes exact attachment bytes', async ({ page }) => {
  await page.goto('/#/resumes');
  await page.getByRole('button', { name: '从示例开始', exact: true }).click();
  await expect(page.getByLabel('副本名称')).toHaveValue('示例简历');
  const firstRoute = page.url();
  await expect(page.frameLocator('iframe').getByRole('heading', { name: /示例用户/ })).toBeVisible();
  await page.locator('iframe').scrollIntoViewIfNeeded();
  await page.screenshot({ path: 'test-results/resumes/desktop.png', fullPage: true });
  const json = page.getByLabel('简历 JSON', { exact: true });
  const source = JSON.parse(await json.inputValue());
  source.name = '虚构浏览器验收'; source.extensionForTest = { keep: true };
  await json.fill(JSON.stringify(source, null, 2));
  await page.getByLabel('副本名称').fill('合成测试简历');
  await page.getByRole('button', { name: '保存修改', exact: true }).click();
  await expect(page.getByText('简历副本已保存。', { exact: true })).toBeVisible();
  await expect(page.frameLocator('iframe').getByRole('heading', { name: '虚构浏览器验收', exact: true })).toBeVisible();
  const initial = resumeDraftSchema.parse(await (await page.request.get(`/api/v1/resume-drafts/${firstRoute.split('/').pop()}`)).json());
  const headers = { Origin: new URL(page.url()).origin };
  const stale = await page.request.patch(`/api/v1/resume-drafts/${initial.id}`, { headers, data: { revision: 1, label: '过期修改', document: initial.document } });
  expect(stale.status()).toBe(409);
  const untrusted = await page.request.post('/api/v1/resume-drafts', { headers: { Origin: 'https://example.test' }, data: { id: crypto.randomUUID(), label: '越界', document: initial.document } });
  expect(untrusted.status()).toBe(403);
  const stranger = await page.context().browser()?.newContext();
  if (!stranger) throw new Error('Missing browser');
  try {
    const response = await stranger.request.get(new URL(`/api/v1/resume-drafts/${initial.id}`, page.url()).href);
    expect(response.status()).toBe(404);
  } finally { await stranger.close(); }

  await json.fill('{ "name": ');
  await expect(page.getByRole('button', { name: '保存修改', exact: true })).toBeDisabled();
  await navigateModule(page, '首页');
  await page.goto(firstRoute);
  await expect(json).toHaveValue('{ "name": ');
  await page.reload();
  await expect(json).toHaveValue('{ "name": ');
  await json.fill(JSON.stringify(initial.document, null, 2));
  await page.getByRole('button', { name: '另存为副本', exact: true }).click();
  await expect(page.getByLabel('副本名称')).toHaveValue('合成测试简历 副本');
  const copyRoute = page.url();
  const copy = JSON.parse(await json.inputValue()); copy.name = '独立岗位副本';
  await json.fill(JSON.stringify(copy, null, 2));
  await page.getByLabel('简历主题').click();
  await page.getByText('松石', { exact: true }).click();
  await page.getByRole('button', { name: '保存修改', exact: true }).click();
  await expect(page.getByText('简历副本已保存。', { exact: true })).toBeVisible();
  await page.goto(firstRoute);
  await expect(page.frameLocator('iframe').getByRole('heading', { name: '虚构浏览器验收', exact: true })).toBeVisible();
  await expect(json).toHaveValue(/extensionForTest/);
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: '导出 PDF', exact: true }).click();
  const pdf = await downloadPromise;
  const path = await pdf.path(); if (!path) throw new Error('Missing PDF download');
  const pdfBytes = await readFile(path);
  expect(pdfBytes.subarray(0, 5).toString()).toBe('%PDF-');
  let responseLost = false;
  await page.route('**/api/v1/resume-versions', async route => {
    if (route.request().method() === 'POST' && !responseLost) {
      responseLost = true;
      expect((await route.fetch()).ok()).toBe(true);
      await route.abort('connectionreset');
    } else await route.continue();
  });
  await page.getByRole('button', { name: '保存为投递版本', exact: true }).click();
  await expect(page.getByRole('button', { name: '重试这个投递版本请求', exact: true })).toBeEnabled({ timeout: 45000 });
  await page.reload();
  await page.getByRole('button', { name: '重试这个投递版本请求', exact: true }).click();
  await expect(page.getByText('已将生成的 PDF 保存为不可变投递版本，可前往投递附件库核对。', { exact: true })).toBeVisible({ timeout: 45000 });
  const versions = resumeVersionListSchema.parse(await (await page.request.get('/api/v1/resume-versions')).json());
  expect(versions).toHaveLength(1);
  const saved = versions.find(version => version.label === '合成测试简历 · 修订 2');
  if (!saved) throw new Error('Missing immutable version');
  const original = await page.request.get(`/api/v1/resume-versions/${saved.id}/original`);
  const originalBytes = await original.body();
  expect(originalBytes.subarray(0, 5).toString()).toBe('%PDF-');
  expect(createHash('sha256').update(originalBytes).digest('hex')).toBe(saved.attachmentSha256);
  const version = await (await page.request.get(`/api/v1/resume-versions/${saved.id}`)).json();
  expect(version.text).toContain('虚构浏览器验收');
  await page.getByRole('button', { name: '删除副本', exact: true }).click();
  await page.getByRole('button', { name: '删除副本', exact: true }).last().click();
  await expect(page).toHaveURL(/#\/resumes$/);
  expect((await page.request.get(`/api/v1/resume-versions/${saved.id}/original`)).status()).toBe(200);
  await page.goto(copyRoute);
  await expect(page.frameLocator('iframe').getByRole('heading', { name: '独立岗位副本', exact: true })).toBeVisible();
});

